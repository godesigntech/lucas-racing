export const FILMS: Film[] = GROUPS.flatMap((g) =>
  g.films.map(([name, pattern, colors, tintable = true], i) => ({
    id: 'f-' + name.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    name,
    category: g.category,
    pattern,
    colors,
    tintable,
    price: g.price + (i % 3) * 5,
    available: true,
    // A handful are "special order" to demonstrate unstocked films routing to quote.
    stocked: !(i % 9 === 8),
  })),
);

export const filmById = (id: string) => FILMS.find((f) => f.id === id);
